    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        
        // Verificamos que no dejen cajas en blanco (el ID Producto no importa porque se genera solo)
        if (!"".equals(txtIdCategoria.getText()) && !"".equals(txtNombre.getText()) && !"".equals(txtPrecio.getText()) && !"".equals(txtStock.getText())) {
            
            // 1. Capturamos el texto de las cajitas y lo metemos al molde "pro"
            pro.setIdCategoria(Integer.parseInt(txtIdCategoria.getText()));
            pro.setNombre(txtNombre.getText());
            pro.setPrecio(Double.parseDouble(txtPrecio.getText()));
            pro.setStock(Integer.parseInt(txtStock.getText()));
            
            // 2. Le decimos al DAO que envíe este molde a Oracle
            if (proDao.registrarProducto(pro)) {
                javax.swing.JOptionPane.showMessageDialog(null, "¡Producto registrado en Oracle con éxito!");
                
                // Limpiamos las cajitas para el siguiente registro
                txtIdCategoria.setText("");
                txtNombre.setText("");
                txtPrecio.setText("");
                txtStock.setText("");
            } else {
                javax.swing.JOptionPane.showMessageDialog(null, "Error al guardar en la base de datos.");
            }
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Cuidado: Llena todos los campos excepto el ID Producto.");
        }
        
        ListarProductos(); // Esto hace que la tabla se actualice sola al instante
    }//GEN-LAST:event_btnGuardarActionPerformed

