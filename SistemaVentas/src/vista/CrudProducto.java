    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
       // Creamos la instancia del DAO aquí mismo para asegurar que funcione
    modelo.ProductoDAO dao = new modelo.ProductoDAO();
    
    // Definimos el modelo de columnas para el reporte
    javax.swing.table.DefaultTableModel modeloReporte = new javax.swing.table.DefaultTableModel();
    modeloReporte.addColumn("ID");
    modeloReporte.addColumn("Producto");
    modeloReporte.addColumn("Categoría");
    modeloReporte.addColumn("Precio S/");
    modeloReporte.addColumn("Stock");
    modeloReporte.addColumn("Valor Total S/");

    // Asignamos el modelo a tu tabla
    tablaProductos.setModel(modeloReporte);

    // Obtenemos la lista de productos con el JOIN desde Oracle
    java.util.List<Object[]> reporte = dao.generarReporteInventario();
    
    // Recorremos los datos y los añadimos fila por fila a la tabla
    for (Object[] fila : reporte) {
        modeloReporte.addRow(fila);
    }

    // Mensaje de éxito
    javax.swing.JOptionPane.showMessageDialog(null, "¡Reporte de inventario generado con éxito desde Oracle!");
    }//GEN-LAST:event_jButton1ActionPerformed

