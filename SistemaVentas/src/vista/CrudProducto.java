    public void ListarProductos() {
    DefaultTableModel modeloTabla = new DefaultTableModel();
    modeloTabla.addColumn("ID Producto");
    modeloTabla.addColumn("ID Categoría");
    modeloTabla.addColumn("Nombre/Modelo");
    modeloTabla.addColumn("Precio");
    modeloTabla.addColumn("Stock");
    tablaProductos.setModel(modeloTabla);

    java.util.List<modelo.Producto> lista = proDao.listarProductos();
    Object[] objeto = new Object[5];
    for (int i = 0; i < lista.size(); i++) {
        objeto[0] = lista.get(i).getId();
        objeto[1] = lista.get(i).getIdCategoria();
        objeto[2] = lista.get(i).getNombre();
        objeto[3] = lista.get(i).getPrecio();
        objeto[4] = lista.get(i).getStock();
        modeloTabla.addRow(objeto);
    }
}

