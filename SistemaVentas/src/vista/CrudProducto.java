    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        // TODO add your handling code here:
        if (!"".equals(txtId.getText()) && !"".equals(txtIdCategoria.getText()) && !"".equals(txtNombre.getText()) && !"".equals(txtPrecio.getText()) && !"".equals(txtStock.getText())) {
        pro.setId(Integer.parseInt(txtId.getText()));
        pro.setIdCategoria(Integer.parseInt(txtIdCategoria.getText()));
        pro.setNombre(txtNombre.getText());
        pro.setPrecio(Double.parseDouble(txtPrecio.getText()));
        pro.setStock(Integer.parseInt(txtStock.getText()));

        if (proDao.actualizarProducto(pro)) {
            javax.swing.JOptionPane.showMessageDialog(null, "¡Producto actualizado con éxito!");
            ListarProductos(); // Refrescamos la tabla
            txtId.setText("");
            txtIdCategoria.setText("");
            txtNombre.setText("");
            txtPrecio.setText("");
            txtStock.setText("");
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al actualizar el producto.");
        }
        } else {
        javax.swing.JOptionPane.showMessageDialog(null, "Selecciona un producto o llena todos los campos incluyendo el ID.");
        }
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (!"".equals(txtId.getText())) {
            int id = Integer.parseInt(txtId.getText());
            int pregunta = javax.swing.JOptionPane.showConfirmDialog(null, "¿Estás seguro de eliminar este producto?");
            if (pregunta == 0) {
                if (proDao.eliminarProducto(id)) {
                    javax.swing.JOptionPane.showMessageDialog(null, "¡Producto eliminado con éxito!");
                    ListarProductos(); // Refrescamos la tabla
                    txtId.setText("");
                    txtIdCategoria.setText("");
                    txtNombre.setText("");
                    txtPrecio.setText("");
                    txtStock.setText("");
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Selecciona o ingresa el ID del producto a eliminar.");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

